LIQUIDS = ('empty', 'water', 'hot_water', 'herbal_bath', 'honey_bath', 'milk_bath', 'peony_bath', 'rose_bath', 'custom')
ROTATION = {'north': 0, 'east': 90, 'south': 180, 'west': 270}

TUB_ITEM_DISPLAY = {
    'gui': {'rotation': [30, 225, 0], 'translation': [2.5, 0, 0], 'scale': [0.35, 0.35, 0.35]},
    'ground': {'rotation': [0, 0, 0], 'translation': [0, 3, 0], 'scale': [0.25, 0.25, 0.25]},
    'fixed': {'rotation': [0, 0, 0], 'translation': [0, 0, 0], 'scale': [0.5, 0.5, 0.5]},
    'thirdperson_righthand': {'rotation': [75, 45, 0], 'translation': [0, 2.5, 0], 'scale': [0.375, 0.375, 0.375]},
    'firstperson_righthand': {'rotation': [0, 45, 0], 'translation': [0, 0, 0], 'scale': [0.4, 0.4, 0.4]},
    'firstperson_lefthand': {'rotation': [0, 225, 0], 'translation': [0, 0, 0], 'scale': [0.4, 0.4, 0.4]},
}


def write_json(path: Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8', newline='\n')


def tub_blockstate(name):
    variants = {}
    for facing, y in ROTATION.items():
        for liquid in LIQUIDS:
            for running in ('false', 'true'):
                for part in ('head', 'foot'):
                    if part == 'foot':
                        model = f'{name}_foot_empty'
                    elif running == 'true' and liquid not in ('empty', 'custom'):
                        model = f'{name}_head_faucet'
                    else:
                        model = f'{name}_head_empty'
                    v = {'model': f'showercore:block/{model}'}
                    if y:
                        v['y'] = y
                    variants[f'facing={facing},part={part},liquid={liquid},running={running}'] = v
    return {'variants': variants}


def facing_blockstate(model):
    return {'variants': {f'facing={facing}': ({'model': model, 'y': y} if y else {'model': model})
                         for facing, y in ROTATION.items()}}


def materials_for(arg, default):
    if arg == 'all':
        return list(ROSTER)
    if arg == 'default':
        return [default]
    return [m.strip() for m in arg.split(',') if m.strip()]


def material_surfaces(boxes, slots):
    # Explicit surface roles survive accents that happen to share a vanilla sprite.
    return [replace(box, faces={name: replace(face, tint=1 if face.tex in slots else 2)
                                for name, face in box.faces.items()}) for box in boxes]


def material_textures(style, material):
    body, accent = ROSTER[material]
    textures = {'body': f'minecraft:block/{body}', 'particle': f'minecraft:block/{body}'}
    if style.trim_from_roster:
        textures['trim'] = f'minecraft:block/{accent}'
    if material == style.default_material:
        # The authored showcase palette is independent of its backwards-compatible item ID.
        textures['body'] = textures['particle'] = style.textures['body']
        if style.trim_from_roster:
            textures['trim'] = style.textures['trim']
    return textures


def generate(project: Path, output: Path, material_arg='default', paint=True):
    version = next(line.split('=', 1)[1].strip() for line in (project / 'gradle.properties').read_text().splitlines()
                   if line.startswith('minecraft_version='))
    light_key = 'forge_data' if version == '1.20.1' else 'neoforge_data'
    assets = output / 'assets/showercore'
    models = assets / 'models'
    report = {'minecraftVersion': version, 'tubs': {}, 'showers': {}, 'warnings': []}

    if paint:
        textures.write_all(assets / 'textures/block/bathroom')

    for style in tubs.STYLES:
        base = f'bathtub_{style.key}'
        full = style.build().boxes
        head, foot = slice_halves(full)
        running_head, _ = slice_halves(style.build(running=True).boxes)
        tex = {**style.textures, 'particle': '#body'}
        for suffix, boxes in (('', full), ('_head_empty', head), ('_head_faucet', running_head), ('_foot_empty', foot)):
            data, issues = model_json(material_surfaces(boxes, style.material_slots), tex, light_key, CREDIT)
            write_json(models / f'block/template/{base}{suffix}.json', data)
            report['warnings'] += [f'{base}{suffix}: z-fight {i}' for i in issues]
        report['tubs'][base] = len(full)
        for material in materials_for(material_arg, style.default_material):
            name = f'{base}_{material}'
            instance = material_textures(style, material)
            for suffix in ('', '_head_empty', '_head_faucet', '_foot_empty'):
                write_json(models / f'block/{name}{suffix}.json',
                           {'parent': f'showercore:block/template/{base}{suffix}', 'textures': instance})
            write_json(assets / f'blockstates/{name}.json', tub_blockstate(name))
            write_json(models / f'item/{name}.json', {'parent': f'showercore:block/{name}', 'display': TUB_ITEM_DISPLAY})

    for style in showers.STYLES:
        base = f'{style.key}_shower_head'
        built = style.build()
        boxes = built.boxes
        bounds = style.profile.validate(built)
        tex = {**style.textures, 'particle': '#body'}
        data, issues = model_json(material_surfaces(boxes, style.material_slots), tex, light_key, CREDIT, render_type=style.render_type,
                                  display=showers.SHOWER_BLOCK_DISPLAY)
        write_json(models / f'block/template/{base}.json', data)
        report['warnings'] += [f'{base}: z-fight {i}' for i in issues]
        report['showers'][base] = {'boxes': len(boxes), 'bounds': bounds}
        for material in materials_for(material_arg, style.default_material):
            name = f'{base}_{material}'
            instance = material_textures(style, material)
            write_json(models / f'block/{name}.json', {'parent': f'showercore:block/template/{base}', 'textures': instance})
            write_json(assets / f'blockstates/{name}.json', facing_blockstate(f'showercore:block/{name}'))
            write_json(models / f'item/{name}.json', {'parent': f'showercore:block/{name}', 'display': showers.SHOWER_ITEM_DISPLAY})

    data, issues = model_json(duck.build().boxes, duck.TEXTURES, light_key, CREDIT, render_type=None,
                              display=None, ambient=False)
    write_json(models / f'block/{duck.NAME}.json', data)
    write_json(models / f'item/{duck.NAME}.json', {'parent': f'showercore:block/{duck.NAME}', 'display': duck.ITEM_DISPLAY})
    if paint:
        duck.paint(assets / 'textures/block' / f'{duck.NAME}.png')
    report['warnings'] += [f'{duck.NAME}: z-fight {i}' for i in issues]
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--output', type=Path, help='resources root (default: src/main/resources)')
    parser.add_argument('--materials', default='default',
                        help="'default' (one showcase material per style), 'all' (33-material roster) or a list")
    parser.add_argument('--no-textures', action='store_true', help='keep existing PNGs (hand edits)')
    args = parser.parse_args(argv)
    report = generate(args.project, args.output or args.project / 'src/main/resources', args.materials,
                      not args.no_textures)
    print(json.dumps(report, indent=2))
